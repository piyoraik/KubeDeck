/// Kubernetes 公式ロゴ（CNCF / The Linux Foundation, CC BY 4.0）。
///
/// 公式 SVG（kubernetes/kubernetes の `logo/logo.svg`）の 2 つのパス
/// ——青い七角形の本体と、白い舵輪——を、絶対座標の `M` / `L` / `C` / `Z` だけに
/// 畳んで単位正方形へ正規化したもの。
///
/// **円弧（`A`）と相対座標は取り込み時に潰してある。** 元データは `a` や `c` を
/// 含むが、円弧を実行時に三次ベジエへ直す処理を持ち込むと、ロゴを描くためだけに
/// SVG の仕様を実装することになる。畳んだ結果を持てば、ここの解釈は 4 命令で足りる。
///
/// 2 つのパスは同じ入れ子にあり同じ transform がかかっていたので、共通の
/// バウンディングボックスで正規化した時点で transform は打ち消えている。
enum KubernetesLogo {
    /// 公式のブランド色 #326CE5。
    static let brandBlue = CGColor(srgbRed: 0.196, green: 0.424, blue: 0.898, alpha: 1)

    // 解析は 1 回だけ。マークは回転のたびに描き直されるので、
    // ここで解析し直すと 6,000 文字超の字句解析が毎フレーム走る。
    // CGPath は作った後は変えないため Sendable 扱いにしてよい。
    private nonisolated(unsafe) static let unitBody = parse(bodyData)
    private nonisolated(unsafe) static let unitWheel = parse(wheelData)

    static func body(in rect: CGRect) -> CGPath { scaled(unitBody, to: rect) }
    static func wheel(in rect: CGRect) -> CGPath { scaled(unitWheel, to: rect) }

    /// 単位正方形のパスを、rect に収まる正方形へ拡大して中央に置く。
    private static func scaled(_ unit: CGPath, to rect: CGRect) -> CGPath {
        let side = min(rect.width, rect.height)
        var transform = CGAffineTransform(
            translationX: rect.midX - side / 2, y: rect.midY - side / 2
        ).scaledBy(x: side, y: side)
        return unit.copy(using: &transform) ?? unit
    }

    /// ロゴを 1 枚のビットマップに焼く。回転を Core Animation に任せるため、
    /// 図形を毎フレーム塗り直さずに済ませるための入口。
    static func image(side: CGFloat, scale: CGFloat) -> CGImage? {
        let pixels = Int((side * scale).rounded())
        guard pixels > 0,
              let context = CGContext(
                data: nil, width: pixels, height: pixels, bitsPerComponent: 8, bytesPerRow: 0,
                space: CGColorSpace(name: CGColorSpace.sRGB)!,
                bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)
        else { return nil }

        // CGContext の原点は左下で Y が上向き。パスは SVG 由来で Y が下向き。
        let size = CGFloat(pixels)
        context.translateBy(x: 0, y: size)
        context.scaleBy(x: 1, y: -1)

        let frame = CGRect(x: 0, y: 0, width: size, height: size)
        context.addPath(body(in: frame))
        context.setFillColor(brandBlue)
        context.fillPath()
        context.addPath(wheel(in: frame))
        context.setFillColor(CGColor(srgbRed: 1, green: 1, blue: 1, alpha: 1))
        context.fillPath()

        return context.makeImage()
    }

    // MARK: - 解釈

    private enum Token {
        case command(Character)
        case number(CGFloat)
    }

    /// 取り込み時に「命令 1 つにつき座標 1 組」へ揃えてあるので、
    /// 命令の省略（同じ命令の繰り返し）は考えなくてよい。
    private static func parse(_ data: String) -> CGPath {
        let path = CGMutablePath()
        let tokens = tokenize(data)
        var index = 0

        func number() -> CGFloat {
            defer { index += 1 }
            guard index < tokens.count, case .number(let value) = tokens[index] else { return 0 }
            return value
        }
        func point() -> CGPoint {
            let x = number()
            return CGPoint(x: x, y: number())
        }

        while index < tokens.count {
            guard case .command(let command) = tokens[index] else {
                index += 1
                continue
            }
            index += 1
            switch command {
            case "M": path.move(to: point())
            case "L": path.addLine(to: point())
            case "C":
                let control1 = point()
                let control2 = point()
                path.addCurve(to: point(), control1: control1, control2: control2)
            case "Z": path.closeSubpath()
            default: break
            }
        }
        return path
    }

    private static func tokenize(_ data: String) -> [Token] {
        var tokens: [Token] = []
        var buffer = ""

        func flush() {
            if !buffer.isEmpty, let value = Double(buffer) {
                tokens.append(.number(CGFloat(value)))
            }
            buffer = ""
        }

        for character in data {
            if character.isLetter {
                flush()
                tokens.append(.command(character))
            } else if character == "-" && !buffer.isEmpty && !buffer.hasSuffix("e") {
                // 区切り無しで次の負数が始まる書き方に備える。
                flush()
                buffer = "-"
            } else if character.isNumber || character == "." || character == "-"
                        || character == "+" || character == "e" {
                buffer.append(character)
            } else {
                flush()
            }
        }
        flush()
        return tokens
    }

